import type { PatternCell, Person, Tense, Unit, UnitStep } from '../src/content/types';
import { cellCardId, wordCardId } from '../src/content/types';
import { lex } from './lexicon';

const w = (...keys: string[]): string[] => keys.map((k) => wordCardId(lex(k).id));
const c = (verb: string, tense: Tense, ...persons: Person[]): string[] =>
  persons.map((p) => cellCardId(verb, tense, p));
const s = (...ids: string[]): string[] => ids.map((id) => `s:${id}`);

const cards = (titleRu: string, ...groups: string[][]): UnitStep => ({
  kind: 'cards',
  titleRu,
  cards: groups.flat(),
});

