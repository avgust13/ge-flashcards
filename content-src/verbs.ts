/**
 * The verified verb table — the single source of every Georgian verb form in
 * the course. Forms are entered by hand and checked by
 * `scripts/content/verify-verbs.ts`; nothing here is derived by rule.
 *
 * Person order in every tuple: 1sg, 2sg, 3sg, 1pl, 2pl, 3pl.
 */
import type { GCase, Person, Screeve, Tense } from '../src/content/types';

export type Six = readonly [string, string, string, string, string, string];

export interface VerbSrc {
  id: string;
  ru: string;
  lemma: string;
  kind: 'action' | 'dative';
  subjectCase: Record<Tense, GCase>;
  pastLabel: 'aorist' | 'imperfect';
  /** Case of the direct object per tense; omitted for verbs that take none. */
  objCase?: Record<Tense, GCase>;
  forms: Record<Tense, Six>;
  /** Optative («чтобы я сделал») — only for verbs the course uses after უნდა / მინდა / შემიძლია. */
  opt?: Six;
  /** Russian verb phrase per cell, without the pronoun. `{а}` or `{он|она}` marks speaker gender. */
  ruForms: Record<Tense, Six>;
  /** Added to the gloss on the card face when two verbs translate alike («говорю (что-то)»). */
  ruHint?: string;
  /** Wiktionary pages whose conjugation tables hold the forms, when one page is not enough (suppletive verbs). */
  wikt?: string[];
  /** Which Russian pronoun set goes in front: я / мне / у меня. */
  ruSubject: 'nom' | 'dat' | 'u';
  /** "быть": Russian present has no verb ("я дома"). */
  zeroCopula?: boolean;
  /** Unit that introduces the cell, or null when the cell is reference only (shown in the matrix, never a card). */
  cellUnit: (t: Screeve, p: Person) => number | null;
  noteRu?: string;
}

const third = (p: Person) => p === '3sg' || p === '3pl';
const sgSpeaker = (p: Person) => p === '1sg' || p === '2sg';

/** Unit 10 teaches the ergative subject; before it, "он / они" are not used in the past. */
const ERG_UNIT = 10;

/** делать / работать / говорить: я-ты in unit 1, the rest in unit 2, 3rd-person past with the ergative in unit 10. */
const coreAction = (optUnit: number) => (t: Screeve, p: Person): number | null =>
  t === 'opt' ? optUnit : sgSpeaker(p) ? 1 : third(p) && t === 'aor' ? ERG_UNIT : 2;

/** A verb met in `unit`: every cell at once, except the 3rd-person past while the ergative is still ahead. */
const from = (unit: number, optUnit: number | null = null) => (t: Screeve, p: Person): number | null =>
  t === 'opt' ? optUnit : third(p) && t === 'aor' && unit < ERG_UNIT ? ERG_UNIT : unit;

/** Intransitive verbs keep a plain subject in every tense, so nothing is held back. */
const fromAll = (unit: number, optUnit: number | null = null) => (t: Screeve): number | null =>
  t === 'opt' ? optUnit : unit;

/** «Мне…» verbs: present, past and future each arrive in their own unit (null = reference only). */
const byTense = (prs: number | null, aor: number | null, fut: number | null) => (t: Screeve): number | null =>
  t === 'prs' ? prs : t === 'aor' ? aor : t === 'fut' ? fut : null;

