/**
 * Compiled course content, as served from `public/content/`.
 * No DOM or `import.meta` usage: this file is shared with the build scripts.
 */

export type Person = '1sg' | '2sg' | '3sg' | '1pl' | '2pl' | '3pl';
export type Tense = 'prs' | 'aor' | 'fut';
/** Rows of a verb that can be a card: the three tenses of the matrix plus the optative. */
export type Screeve = Tense | 'opt';
export type Polarity = 'aff' | 'neg' | 'q';
export type GCase = 'nom' | 'erg' | 'dat';
export type ReviewStatus = 'verified' | 'auto-verified' | 'needs-review';
export type CellKey = `${Screeve}.${Person}`;

export const PERSONS: readonly Person[] = ['1sg', '2sg', '3sg', '1pl', '2pl', '3pl'];
export const TENSES: readonly Tense[] = ['prs', 'aor', 'fut'];
/** Matrix rows top to bottom: future, present, past. */
export const TENSE_ROWS: readonly Tense[] = ['fut', 'prs', 'aor'];
export const SCREEVES: readonly Screeve[] = ['prs', 'aor', 'fut', 'opt'];
/** The optative belongs to the same series as the aorist: same subject and object cases. */
export const seriesTense = (s: Screeve): Tense => (s === 'opt' ? 'aor' : s);

export const TENSE_RU: Record<Screeve, string> = {
  fut: 'Будущее',
  prs: 'Настоящее',
  aor: 'Прошедшее',
  opt: 'Чтобы…',
};

export const PERSON_RU: Record<Person, string> = {
  '1sg': 'я',
  '2sg': 'ты',
  '3sg': 'он',
  '1pl': 'мы',
  '2pl': 'вы',
  '3pl': 'они',
};

export interface Verb {
  id: string;
  /** Russian infinitive: "делать". */
  ru: string;
  /** Dictionary form (3sg present): აკეთებს. */
  lemma: string;
  /** `dative` = "мне…"-verbs whose logical subject stands in the dative. */
  kind: 'action' | 'dative';
  /** Case of a 3rd-person subject in each tense. */
  subjectCase: Record<Tense, GCase>;
  /** What the "past" row actually is for this verb. */
  pastLabel: 'aorist' | 'imperfect';
  /** Case of the direct object in each tense; null for verbs that take none. */
  objCase: Record<Tense, GCase> | null;
  /** The 18 stored forms. Never generated by rule. */
  forms: Record<Tense, Record<Person, string>>;
  /** Optative («чтобы я сделал»), stored only for verbs used after უნდა / მინდა / შემიძლია. */
  opt: Record<Person, string> | null;
  /** Russian gloss of each cell: "я делаю". May contain the `{а}` speaker-gender marker. */
  ruCells: Record<Tense, Record<Person, string>>;
  ruOpt: Record<Person, string> | null;
  /** Unit that introduces each cell. A missing key means "later in the course". */
  cellUnit: Partial<Record<CellKey, number>>;
  status: Partial<Record<CellKey, ReviewStatus>>;
  noteRu: string | null;
}

/**
 * Named surfaces of a word besides its dictionary form: cases (`dat`, `erg`,
 * `gen`, `ins`, `adv`), the plural (`pl`), postpositions (`shi` в, `ze` на,
 * `dan` из, `tan` у/к, `tvis` для), `cop` — with the short «есть» (კარგია).
 */
export type KaForm = 'dat' | 'erg' | 'gen' | 'ins' | 'adv' | 'pl' | 'shi' | 'ze' | 'dan' | 'tan' | 'tvis' | 'cop';
export type LexStatus = 'verified' | 'attested' | 'needs-review';

export interface Lexeme {
  id: number;
  ka: string;
  ru: string;
  unit: number;
  note: string | null;
  /** Other surfaces of the word that sentences may use (e.g. with a postposition: სახლში). */
  forms: string[];
  /** The same surfaces by name. */
  cases: Partial<Record<KaForm, string>>;
  /** Weakest evidence among the word's surfaces (Wiktionary table / corpus list). */
  status: LexStatus;
}

export type TokenRole = 'verb' | 'subj' | 'neg' | 'adv' | 'obj' | 'place' | 'qword' | 'attr' | 'other';

export interface Token {
  /** One orthographic word = one tile. Postpositions stay attached. */
  t: string;
  role: TokenRole;
  /** Plausible wrong forms of this token, for distractors and decoy tiles. */
  alts?: string[];
  /** Pattern card this token is the instance of (`c:dat`): the place where that card is tested. */
  pat?: string;
  /** Lexeme this token is a surface of, and which one (`nom` when omitted). */
  lex?: number;
  form?: KaForm;
  /** Verb cell this token is the form of: `do.opt.1sg`. */
  cell?: string;
  /** Punctuation written right after the word (a comma between clauses). Not part of the tile. */
  after?: string;
}

/** The written sentence: its words, the punctuation between them, and the final mark. */
export const joinTokens = (tokens: Pick<Token, 't' | 'after'>[], end: string): string =>
  tokens.map((t) => t.t + (t.after ?? '')).join(' ') + end;

export interface Sentence {
  id: string;
  unit: number;
  /** Card this sentence primarily exercises: `c:work.prs.1sg` or `s:<id>` for fixed phrases. */
  focus: string;
  /** Template id. Sentences sharing a verb and a frame are natural distractors for each other. */
  frame: string;
  verb: string | null;
  tense: Screeve | null;
  person: Person | null;
  polarity: Polarity;
  /** true: one fixed word order (two clauses, two verbs, a line of a dialogue). */
  strict?: boolean;
  ka: string;
  /** Russian prompt. May contain the `{а}` speaker-gender marker. */
  ru: string;
  tokens: Token[];
  /** Other cards that must already be introduced before this sentence may be shown. */
  req: string[];
  /** true: the sentence is a card of its own (greetings, set phrases). */
  fixed: boolean;
}

export interface PatternCell {
  /** Card id without the `c:` prefix: `neg`, `q`, `shi`, `ze`. */
  id: string;
  unit: number;
  titleRu: string;
  noteRu: string;
}

export interface ExplainStep {
  kind: 'explain';
  id: string;
  titleRu: string;
  bodyRu: string[];
  /** `who` labels the speaker when the examples are the lines of a dialogue. */
  examples: { ka: string; ru: string; who?: string }[];
}

export interface CardsStep {
  kind: 'cards';
  titleRu: string;
  /** Card ids in introduction order: `w:<lexId>`, `c:<cell>`, `s:<sentenceId>`. */
  cards: string[];
}

export type UnitStep = ExplainStep | CardsStep;

export interface Unit {
  id: number;
  titleRu: string;
  goalRu: string;
  /** false: the unit is on the roadmap but has no content yet. */
  ready: boolean;
  steps: UnitStep[];
}

export interface Letter {
  /** The Mkhedruli letter. */
  ch: string;
  /** Latin transliteration, same scheme as `translit()`. */
  tr: string;
  /** Short Russian label of the sound; unique per letter (тʰ vs т’). */
  ru: string;
  /** How it sounds / how to say it. */
  hintRu: string;
  /** Teaching group, 1..6, in order of introduction. */
  group: number;
  /** Letters that look similar — distractors when reading. */
  lookAlike: string[];
  /** Letters that sound similar — distractors when listening. */
  soundAlike: string[];
  /** Text of the letter's audio clip: the vowel itself or the syllable "…ა". */
  say: string;
  /** A common word that starts with the letter. */
  word: { ka: string; ru: string };
}

export interface LetterGroup {
  id: number;
  titleRu: string;
  noteRu: string;
}

export interface PairWord {
  ch: string;
  ka: string;
  ru: string;
}

/** Two words that differ only in one consonant of a confusable pair. */
export interface LetterPair {
  a: PairWord;
  b: PairWord;
}

export interface Course {
  version: string;
  units: Unit[];
  verbs: Verb[];
  lexicon: Lexeme[];
  patterns: PatternCell[];
  letters: Letter[];
  letterGroups: LetterGroup[];
  letterPairs: LetterPair[];
}

export const cellCardId = (verbId: string, tense: Screeve, person: Person): string =>
  `c:${verbId}.${tense}.${person}`;
export const CELL_RE = /^c:([a-z0-9]+)\.(prs|aor|fut|opt)\.(1sg|2sg|3sg|1pl|2pl|3pl)$/;

/** The stored form of a cell, or undefined when the verb has no such row. */
export const verbForm = (v: Verb, s: Screeve, p: Person): string | undefined =>
  s === 'opt' ? v.opt?.[p] : v.forms[s][p];
export const verbRu = (v: Verb, s: Screeve, p: Person): string =>
  (s === 'opt' ? v.ruOpt?.[p] : v.ruCells[s][p]) ?? '';
/** Sentence-final mark of a compiled sentence: ".", "?" or "!". */
export const endMark = (ka: string): string => ka.slice(-1);
export const wordCardId = (lexId: number): string => `w:${lexId}`;
export const letterCardId = (ch: string): string => `l:${ch}`;
